"""pipeline/align.py — word timestamps, the ONE alignment run (stage P4).

Usage:
  .venv/Scripts/python.exe pipeline/align.py --video <id> [--rebuild]

Runs the vendored kit's tools/transcribe.py (faster-whisper, script-as-truth) inside the
generated studio project, then:
  1. copies the EXACT plugin-format words.json to videos/<id>/timeline/words.json (canonical)
  2. parses the printed "script alignment: X/Y (Z%)" and enforces the >=95% rule
     (the plugin does NOT enforce it in code — we do)
  3. writes videos/<id>/timeline/align_report.json

words.frames.json is generated by pipeline/make_plugin_files.py once master.json exists
(it needs segment boundaries to call each frame range's segmentId).
"""

import argparse
import os
import re
import shutil
import sys

from _common import (ROOT, VIDEOS, load_config, run, video_dir,
                     studio_project, save_json)

KIT_TRANSCRIBE = os.path.join(ROOT, "studio", "tools", "transcribe.py")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--video", required=True)
    a = ap.parse_args()

    cfg = load_config()
    vdir = video_dir(a.video)
    pdir = studio_project(a.video)
    if not os.path.isdir(pdir):
        sys.exit(f"studio project missing: {pdir} — run pipeline/make_plugin_files.py --video {a.video} first")

    script = os.path.join(vdir, "script.txt")
    if not os.path.exists(script):
        sys.exit(f"missing {script} (Stage P2 writes it)")

    # run the kit's verified transcription/alignment exactly as designed
    p = run([sys.executable, KIT_TRANSCRIBE, "--project", pdir,
             "--model", cfg["align"]["model"],
             "--lang", "en",
             "--script", script], check=False)
    out = p.stdout or ""
    print(out[-3000:])
    if p.returncode != 0:
        sys.exit(f"transcribe failed: {(p.stderr or '')[-1500:]}")

    m = re.search(r"script alignment:\s*(\d+)/(\d+)\s+[^)]*\((\d+)%\)", out)
    if not m:
        sys.exit("could not parse alignment report from transcribe.py output")
    matched, total, pct = int(m.group(1)), int(m.group(2)), int(m.group(3))
    min_pct = int(cfg["align"]["min_match_pct"])

    # canonical copy (EXACT plugin format, copied verbatim — never edited by hand)
    tdir = os.path.join(vdir, "timeline")
    os.makedirs(tdir, exist_ok=True)
    for name in ("words.json", "sentences.json", "transcript.txt"):
        src = os.path.join(pdir, "timeline", name)
        if os.path.exists(src):
            shutil.copy2(src, os.path.join(tdir, name))

    save_json(os.path.join(tdir, "align_report.json"), {
        "model": cfg["align"]["model"],
        "match_pct": pct,
        "matched": matched,
        "total": total,
        "min_pct": min_pct,
        "passed": bool(pct >= min_pct),
        "canonical_words": "timeline/words.json",
        "notes": "match uses numeric-value parity (whisper transcribes spoken numbers as digits; both sides canon to digits). Hyphenated compounds (e.g. 'light-years') scan as one script word vs two heard words — known acceptable miss.",
    })
    if pct < min_pct:
        sys.exit(f"ALIGNMENT GATE FAILED: {pct}% < {min_pct}% — re-record/fix script or voice before continuing")
    print(f"alignment ok: {pct}% (>= {min_pct}%)  words -> videos/{a.video}/timeline/words.json")


if __name__ == "__main__":
    main()
